/**
 * Builds src/lib/whatsnew.generated.ts from docs/changelog/v*.md so the app can show
 * release notes offline (About page). Run after editing changelog files; CI runs it too.
 */
/* global __dirname */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'docs', 'changelog');
const out = path.join(root, 'src', 'lib', 'whatsnew.generated.ts');

const parse = (v) => v.split('.').map((n) => parseInt(n, 10) || 0);
const cmp = (a, b) => {
  const pa = parse(a);
  const pb = parse(b);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
};

const releases = fs
  .readdirSync(dir)
  .map((f) => /^v(\d+\.\d+\.\d+)\.md$/.exec(f))
  .filter(Boolean)
  .map((m) => ({ version: m[1], notes: fs.readFileSync(path.join(dir, m[0]), 'utf8').trim() }))
  .sort((a, b) => cmp(b.version, a.version));

const body =
  '// Generated by scripts/gen-whatsnew.js from docs/changelog. Do not edit by hand.\n' +
  `export const RELEASES: readonly { version: string; notes: string }[] = ${JSON.stringify(releases, null, 2)};\n`;
fs.writeFileSync(out, body);
console.log(`[gen-whatsnew] ${releases.length} releases -> ${path.relative(root, out)}`);
